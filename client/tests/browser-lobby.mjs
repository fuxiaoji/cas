import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
import { signInLocal } from './browser-login.mjs';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.CAS_PLAYWRIGHT_MODULE || 'playwright');
const root = process.env.CAS_ARTIFACTS || 'artifacts/client/lobby/';
await fs.mkdir(root, { recursive: true });
const errors = [];
const browser = await chromium.launch({ executablePath: process.env.CAS_BROWSER_PATH, headless: true });
const page = await (await browser.newContext({ viewport: { width: 1360, height: 768 } })).newPage();
page.on('pageerror', error => errors.push(error.stack));
try {
  await page.goto('http://127.0.0.1:5175/');
  await signInLocal(page, 'cas-lobby-' + Date.now().toString(36), true);
  await page.locator('.growth-port').waitFor();
  console.log('port wallet', await page.locator('.growth-wallet').innerText());
  const dock = await page.locator('.growth-dock > button').count();
  assert.equal(dock, 4);
  await page.screenshot({ path: root + 'mother-port.png' });
  await page.locator('.growth-campaign-entry').click();
  await page.locator('.campaign-lobby').waitFor();
  await page.getByRole('button', { name: '战区总览', exact: true }).click();
  await page.locator('.cl-row').first().waitFor();
  const entries = await page.locator('.cl-row').count();
  const stars = await page.locator('.cl-stars').innerText();
  assert.equal(entries, 11);
  assert.match(stars, /0 \/ 33/);
  await page.screenshot({ path: root + 'campaign-lobby.png' });
  await page.getByRole('button', { name: '编成出击', exact: true }).click();
  await page.locator('.deployment-screen').waitFor();
  await page.locator('.dep-slot').first().waitFor();
  console.log('deployment title', await page.locator('.dep-title h1').innerText());
  await page.screenshot({ path: root + 'campaign-deployment.png' });
  await page.locator('.dep-back').click();
  await page.locator('.campaign-lobby').waitFor();
  await page.setViewportSize({ width: 740, height: 360 });
  const horizontalOverflow = await page.evaluate(() =>
    document.documentElement.scrollWidth > window.innerWidth || document.body.scrollWidth > window.innerWidth);
  assert.equal(horizontalOverflow, false, 'the 740px lobby must not scroll horizontally');
  await page.screenshot({ path: root + 'campaign-lobby-740.png' });
  await page.setViewportSize({ width: 1360, height: 768 });
  await page.getByRole('button', { name: '剧情模式', exact: true }).click();
  await page.locator('.story-mode').waitFor();
  console.log('story chapters', await page.locator('.story-chapters li > button').count());
  await page.screenshot({ path: root + 'story-mode.png' });
  await page.getByRole('button', { name: /序章 · 未明的海/ }).first().click();
  await page.locator('.prologue-scene').waitFor();
  console.log('prologue opened');
  await page.screenshot({ path: root + 'prologue.png' });
  assert.deepEqual(errors, []);
  await fs.writeFile(root + 'browser-receipt.json', JSON.stringify({ ok: true, dock, entries, stars, story: 'prologue-opened' }, null, 2));
} finally { await browser.close(); }
