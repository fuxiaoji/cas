def table(headers, rows, widths, size=9, head_fill=HEX_NAVY, first_bold=True):
    total = float(sum(widths))
    usable = 16.3
    widths = [w * usable / total for w in widths]
    t = doc.add_table(rows=1, cols=len(headers))
    t.autofit = False
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    table_borders(t)
    cell_margins(t)
    for i, wcm in enumerate(widths):
        t.columns[i].width = Cm(wcm)
    hdr = t.rows[0]
    repeat_header(hdr)
    for i, text in enumerate(headers):
        cell = hdr.cells[i]
        cell.width = Cm(widths[i])
        shade(cell, head_fill)
        p = cell.paragraphs[0]
        p.paragraph_format.space_after = Pt(0)
        p.paragraph_format.line_spacing = 1.2
        r = p.add_run(text)
        set_run_font(r, size=size, bold=True, color=RGBColor(0xFF, 0xFF, 0xFF))
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        keep_row_together(t.rows[-1])
        for i, text in enumerate(row):
            cell = cells[i]
            cell.width = Cm(widths[i])
            if ri % 2 == 1:
                shade(cell, HEX_BAND)
            p = cell.paragraphs[0]
            p.paragraph_format.space_after = Pt(0)
            p.paragraph_format.line_spacing = 1.25
            bold = first_bold and i == 0
            rich(p, text, size=size, color=INK)
            if bold:
                for run in p.runs:
                    run.font.bold = True
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


