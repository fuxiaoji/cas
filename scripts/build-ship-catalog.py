#!/usr/bin/env python3
"""Project the 210 stable IBS-U-* identities into client/src/ship-catalog.ts.

Sources (read only):
  data/ships/cards.json                    210 identity rows, 202 playable / 8 collection
  data/rules/cas-competitive-points-v1.json  one point row per playable identity

The generated TypeScript module is the client-side single-ship catalogue used by
the local recruit desk, the harbour fleet editor and the quartermaster.  Nothing
here changes data/ships or the point manifest.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CARDS = ROOT / "data/ships/cards.json"
POINTS = ROOT / "data/rules/cas-competitive-points-v1.json"
OUT = ROOT / "client/src/ship-catalog.ts"

# The source stores gacha_rarity as common/rare/elite/ur (no SSR/SR text).
# The client keeps those four internal tiers and only relabels them for display.
RARITIES = {"common", "rare", "elite", "ur"}
RARITY_LABELS = {"common": "R", "rare": "SR", "elite": "SSR", "ur": "UR"}

# Five starter hulls per side.  Every id is validated below against cards.json.
STARTER = {
    "allies": [
        "IBS-U-USN-FLETCHER",
        "IBS-U-USN-PERKINS",
        "IBS-U-USN-MAURY",
        "IBS-U-USN-DRAYTON",
        "IBS-U-USN-HONOLULU",
    ],
    "axis": [
        "IBS-U-IJN-KAGERO",
        "IBS-U-IJN-TAKANAMI",
        "IBS-U-IJN-OYASHIO",
        "IBS-U-IJN-KUROSHIO",
        "IBS-U-IJN-SENDAI",
    ],
}

# The local UP banner is Missouri.  Both pools draw from all 202 playable
# identities; the UP pool only adds the banner's 50% share of the UR tier.
FEATURED = "IBS-U-USN-ERMA-MISSOURI"

# Axis battleships are flagged `rare` in cards.json, but the local gacha treats
# them as UR.  The override lives in this projection only; data/ships is read-only.
AXIS_BB_OVERRIDE = "ur"


def fail(message: str) -> None:
    raise SystemExit("build-ship-catalog: " + message)


def main() -> None:
    cards_doc = json.loads(CARDS.read_text(encoding="utf-8"))
    cards = cards_doc["cards"]
    points_doc = json.loads(POINTS.read_text(encoding="utf-8"))
    points = points_doc["ships"]

    if len(cards) != 210:
        fail(f"expected 210 identities, got {len(cards)}")
    identities = [row["identity"] for row in cards]
    if len(set(identities)) != len(identities):
        fail("duplicate identity in cards.json")

    gacha_values = {row.get("gacha_rarity") for row in cards}
    if gacha_values != RARITIES:
        fail(f"unexpected gacha_rarity set: {sorted(gacha_values)}")
    display_values = {row.get("display_rarity") for row in cards}
    if not display_values <= RARITIES:
        fail(f"unexpected display_rarity set: {sorted(display_values)}")

    playable = [row for row in cards if row.get("playable") is True]
    if len(playable) != 202:
        fail(f"expected 202 playable identities, got {len(playable)}")

    missing_points = [row["identity"] for row in playable if row["identity"] not in points]
    if missing_points:
        fail(f"playable identities without a point row: {missing_points}")

    by_id = {row["identity"]: row for row in cards}
    for side, ids in STARTER.items():
        if len(ids) != 5:
            fail(f"starter {side} must hold five identities")
        for identity in ids:
            row = by_id.get(identity)
            if row is None:
                fail(f"starter identity missing from cards.json: {identity}")
            if row.get("side") != side or row.get("playable") is not True:
                fail(f"starter identity is not a playable {side} hull: {identity}")
        if len(set(ids)) != 5:
            fail(f"starter {side} repeats an identity")

    def effective_rarity(row: dict) -> str:
        if row.get("side") == "axis" and row.get("type") == "BB":
            return AXIS_BB_OVERRIDE
        return row["gacha_rarity"]

    featured = by_id.get(FEATURED)
    if featured is None or featured.get("playable") is not True or featured.get("side") != "allies":
        fail(f"featured identity is not a playable allied hull: {FEATURED}")
    if effective_rarity(featured) != "ur":
        fail("the Missouri banner must be UR")

    axis_bb = [row for row in playable if row.get("side") == "axis" and row.get("type") == "BB"]
    if len(axis_bb) != 7:
        fail(f"expected seven playable axis battleships to override to UR, got {len(axis_bb)}")
    wrong = [row["identity"] for row in axis_bb if row.get("gacha_rarity") != "rare"]
    if wrong:
        fail(f"axis BB override expects the source rows to be rare: {wrong}")

    def ts_string(value: str) -> str:
        return json.dumps(value, ensure_ascii=False)

    lines: list[str] = []
    lines.append("// Generated by scripts/build-ship-catalog.py — do not edit by hand.")
    lines.append("// Sources: data/ships/cards.json (210 identities) and")
    lines.append("// data/rules/cas-competitive-points-v1.json (one point row per playable hull).")
    lines.append("// 202 identities are playable; the 8 collection-only identities stay out of")
    lines.append("// the recruit pool (see data/ships/merge-report.json).")
    lines.append("")
    lines.append("export type ShipSide = 'allies' | 'axis';")
    lines.append("export type ShipRarity = 'common' | 'rare' | 'elite' | 'ur';")
    lines.append("")
    lines.append("export interface ShipCard {")
    lines.append("  id: string;")
    lines.append("  name: string;")
    lines.append("  side: ShipSide;")
    lines.append("  type: string;")
    lines.append("  class: string | null;")
    lines.append("  classId: string | null;")
    lines.append("  rarity: ShipRarity;")
    lines.append("  gachaRarity: ShipRarity;")
    lines.append("  playable: boolean;")
    lines.append("  points?: number;")
    lines.append("}")
    lines.append("")
    lines.append("export const SHIPS: readonly ShipCard[] = [")
    for row in cards:
        identity = row["identity"]
        rarity = effective_rarity(row)
        entry = {
            "id": identity,
            "name": row.get("name") or identity,
            "side": row["side"],
            "type": row["type"],
            "class": row.get("class"),
            "classId": row.get("cas_source_class"),
            "rarity": rarity,
            "gachaRarity": rarity,
            "playable": bool(row.get("playable")),
        }
        if identity in points:
            entry["points"] = int(points[identity]["points"])
        lines.append("  { " + ", ".join(
            f"{key}: {ts_string(value) if isinstance(value, str) else json.dumps(value)}"
            for key, value in entry.items()
        ) + " },")
    lines.append("];")
    lines.append("")
    lines.append("export const PLAYABLE_SHIPS: readonly ShipCard[] = SHIPS.filter(ship => ship.playable);")
    lines.append("")
    lines.append("export const STARTER_SHIPS: Record<ShipSide, readonly string[]> = {")
    for side in ("allies", "axis"):
        lines.append(f"  {side}: [")
        for identity in STARTER[side]:
            lines.append(f"    {ts_string(identity)},")
        lines.append("  ],")
    lines.append("};")
    lines.append("")
    lines.append("export const FEATURED_SHIP: string = " + ts_string(FEATURED) + ";")
    lines.append("")
    lines.append("// Both pools hold all 202 playable identities; the UP pool only adds the")
    lines.append("// featured hull's 50% share of its UR tier.  The array keeps the old export")
    lines.append("// shape for callers that want to render the banner list.")
    lines.append("export const FEATURED_SHIPS: readonly string[] = [FEATURED_SHIP];")
    lines.append("")
    lines.append("const BY_ID = new Map(SHIPS.map(ship => [ship.id, ship]));")
    lines.append("")
    lines.append("export function shipCard(id: string | null | undefined): ShipCard | undefined {")
    lines.append("  return id ? BY_ID.get(id) : undefined;")
    lines.append("}")
    lines.append("")
    lines.append("export function shipName(id: string | null | undefined): string {")
    lines.append("  return shipCard(id)?.name ?? (id || '未登记舰');")
    lines.append("}")
    lines.append("")
    lines.append("const TYPE_NAMES: Record<string, string> = {")
    for code, name in [
        ("DD", "驱逐舰"),
        ("CL", "轻巡洋舰"),
        ("CA", "重巡洋舰"),
        ("CB", "大型巡洋舰"),
        ("BC", "战列巡洋舰"),
        ("BB", "战列舰"),
        ("CV", "航空母舰"),
        ("AV", "水上机母舰"),
        ("APD", "快速运输舰"),
    ]:
        lines.append(f"  {ts_string(code)}: {ts_string(name)},")
    lines.append("};")
    lines.append("")
    lines.append("export function shipTypeName(type: string | null | undefined): string {")
    lines.append("  return (type && TYPE_NAMES[type]) || type || '舰种未登记';")
    lines.append("}")
    lines.append("")
    lines.append("export const RARITY_LABELS: Record<ShipRarity, string> = {")
    for rarity in ("common", "rare", "elite", "ur"):
        lines.append(f"  {rarity}: {ts_string(RARITY_LABELS[rarity])},")
    lines.append("};")
    lines.append("")
    lines.append("export function shipRarityName(rarity: ShipRarity | null | undefined): string {")
    lines.append("  return rarity ? RARITY_LABELS[rarity] : '—';")
    lines.append("}")
    lines.append("")
    lines.append("export function shipPoints(id: string | null | undefined): number {")
    lines.append("  return shipCard(id)?.points ?? 0;")
    lines.append("}")
    lines.append("")
    lines.append("export function shipsBySide(side: ShipSide, playableOnly = true): ShipCard[] {")
    lines.append("  return SHIPS.filter(ship => ship.side === side && (!playableOnly || ship.playable));")
    lines.append("}")
    lines.append("")

    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(cards)} identities, {len(playable)} playable)")


if __name__ == "__main__":
    main()
